"""
Agent 评测：小评测集回归
============================================================
LLM 输出有随机性，改一次提示词、换一次模型都可能悄悄破坏原有能力。
评测集就是 Agent 的"回归测试"：固定一组问题与判定标准，每次改动后
重跑，量化四个指标：成功率、轮数、耗时、词元消耗。

判定方式为关键词包含——粗糙但零成本、无歧义；进阶做法（用另一个
LLM 当裁判）留待需要时引入。

运行：python3 eval.py   （需要 8001/8002 两个服务在运行）
"""
import time

from agent import 运行Agent

评测集 = [
    {"问题": "现在全网退服总数是多少个？", "应包含": ["153"]},
    {"问题": "哪个地市退服最多？", "应包含": ["南京"]},
    {"问题": "告警分为哪几个等级？", "应包含": ["紧急", "重要", "次要", "提示"]},
    {"问题": "按规范，多少个站以上算批量退服？该怎么办？", "应包含": ["10", "应急预案"]},
]

if __name__ == "__main__":
    记录 = []
    for 序, 用例 in enumerate(评测集, 1):
        起点 = time.time()
        try:
            结果 = 运行Agent(用例["问题"])
        except Exception as 错:
            结果 = {"answer": f"[异常] {错}", "rounds": 0, "tokens": 0}
        耗时 = time.time() - 起点
        答案 = 结果.get("answer") or ""
        通过 = all(词 in 答案 for 词 in 用例["应包含"])
        记录.append((通过, 结果.get("rounds", 0), 耗时, 结果.get("tokens", 0)))
        print(f"[{序}/{len(评测集)}] {'通过' if 通过 else '未通过'} | "
              f"{结果.get('rounds', 0)} 轮 | {耗时:.1f} 秒 | {结果.get('tokens', 0)} 词元 | {用例['问题']}")
        if not 通过:
            print(f"      缺少关键词：{[词 for 词 in 用例['应包含'] if 词 not in 答案]}")
            print(f"      答案节选：{答案[:120]}")

    通过数 = sum(1 for 过, *_ in 记录 if 过)
    print("\n===== 汇总 =====")
    print(f"成功率：{通过数}/{len(记录)}（{通过数 / len(记录):.0%}）")
    print(f"平均轮数：{sum(轮 for _, 轮, _, _ in 记录) / len(记录):.1f}")
    print(f"平均耗时：{sum(秒 for _, _, 秒, _ in 记录) / len(记录):.1f} 秒")
    print(f"词元合计：{sum(词 for _, _, _, 词 in 记录)}")
